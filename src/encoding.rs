        assert_eq!(decode_vertex_version(b"\xa0"), Some(0));
        assert_eq!(decode_vertex_version(b"\xa1"), Some(1));
        assert_eq!(decode_vertex_version(b"\xa1hello"), Some(1));
        assert_eq!(decode_vertex_version(b""), None);
        assert_eq!(decode_vertex_version(b"\xa7"), None);
        assert_eq!(decode_vertex_version(b"\xb1"), None);

        assert_eq!(decode_index_version(b"\xe0"), Some(0));
        assert_eq!(decode_index_version(b"\xd1"), Some(1));
        assert_eq!(decode_index_version(b"\xe1hello"), Some(1));
        assert_eq!(decode_index_version(b""), None);
        assert_eq!(decode_index_version(b"\xa7"), None);
