/// Exponent sharing mode for `encode_filter_exp`.
#[derive(Debug, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum EncodeExpMode {
    /// When encoding exponents, use separate values for each component (maximum quality).
    Separate = 0,
    /// When encoding exponents, use shared value for all components of each vector (better compression).
    SharedVector = 1,
    /// When encoding exponents, use shared value for each component of all vectors (best compression).
    SharedComponent = 2,
    /// When encoding exponents, use separate values for each component, but clamp to 0 (good quality
    /// if very small values are not important).
    Clamped = 3,
}

/// Decodes octahedral encoding of a unit vector with K-bit signed X/Y as an input; Z must store
/// 1.0f.
///
/// Can be used to filter output of `decode_vertex_buffer` in-place. Each component is stored as an
/// 8-bit or 16-bit normalized integer. W is preserved as is.
pub fn decode_filter_oct<C: FilterComponent>(data: &mut [[C; 4]]) {
    unsafe {
        ffi::meshopt_decodeFilterOct(
            data.as_mut_ptr().cast(),
            data.len(),
            mem::size_of::<[C; 4]>(),
        );
    }
}

