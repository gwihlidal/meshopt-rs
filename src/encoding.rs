/// Encodes vertex data into an array of bytes that is generally smaller and compresses better
/// compared to original.
///
/// This function works for a single vertex stream; for multiple vertex streams,
/// call `encode_vertex_buffer` for each stream.
pub fn encode_vertex_buffer<T>(vertices: &[T]) -> Result<Vec<u8>> {
    let bounds =
        unsafe { ffi::meshopt_encodeVertexBufferBound(vertices.len(), mem::size_of::<T>()) };
    let mut result: Vec<u8> = vec![0; bounds];
    let size = unsafe {
        ffi::meshopt_encodeVertexBuffer(
            result.as_mut_ptr(),
            result.len(),
            vertices.as_ptr().cast(),
            vertices.len(),
            mem::size_of::<T>(),
        )
    };
    result.resize(size, 0u8);
    Ok(result)
}

/// Encodes vertex data just like `encode_vertex_buffer`, but allows to override compression level.
///
/// For compression level to take effect, the vertex encoding version must be set to 1.
/// The default compression level implied by `encode_vertex_buffer` is 2.
///
/// * `level` should be in the range [0, 3] with 0 being the fastest and 3 being the slowest and
///   producing the best compression ratio.
/// * `version` should be `None` to use the default version, or `Some(0)`/`Some(1)` to override the
///   version; per above, level won't take effect if version is 0.
pub fn encode_vertex_buffer_level<T>(
    vertices: &[T],
    level: i32,
    version: Option<i32>,
) -> Result<Vec<u8>> {
    let bounds =
        unsafe { ffi::meshopt_encodeVertexBufferBound(vertices.len(), mem::size_of::<T>()) };
    let mut result: Vec<u8> = vec![0; bounds];
    let size = unsafe {
        ffi::meshopt_encodeVertexBufferLevel(
            result.as_mut_ptr(),
            result.len(),
            vertices.as_ptr().cast(),
            vertices.len(),
            mem::size_of::<T>(),
            level,
            version.unwrap_or(-1),
        )
    };
    result.resize(size, 0u8);
    Ok(result)
}

