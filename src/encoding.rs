        let encoded_indices = encode_index_buffer(&indices, 4).unwrap();
        let encoded_sequence = encode_index_sequence(&indices, 4).unwrap();
        unsafe { encode_index_version(1) };

        assert_eq!(decode_index_version(&encoded_indices), Some(0));
        assert_eq!(decode_index_version(&encoded_sequence), Some(0));

