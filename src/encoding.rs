/// Encodes meshlet data into an array of bytes that is generally smaller and compresses better
/// compared to original.
///
/// This function encodes a single meshlet; when encoding multiple meshlets, additional headers may
/// be necessary to store vertex/triangle count and encoded size.
///
/// For maximum efficiency the meshlet being encoded should be optimized using
/// `optimize_meshlet_level` with level 1+ (3 recommended); additionally, vertex reference data
/// should be optimized for locality (fetch).
///
/// * `meshlet.vertices` may be empty, in which case only triangle data is encoded
/// * vertex and triangle counts must be <= 256
pub fn encode_meshlet(meshlet: Meshlet<'_>) -> Result<Vec<u8>> {
    let vertex_count = meshlet.vertices.len();
    let triangle_count = meshlet.triangles.len() / 3;
    if !meshlet.triangles.len().is_multiple_of(3) {
        return Err(Error::memory(
            "meshlet triangle index count must be a multiple of 3",
        ));
    }
    if vertex_count > 256 || triangle_count > 256 {
        return Err(Error::memory(
            "meshlet vertex and triangle counts must be at most 256",
        ));
    }
    let bounds = unsafe { ffi::meshopt_encodeMeshletBound(vertex_count, triangle_count) };
    let mut result: Vec<u8> = vec![0; bounds];
    let size = unsafe {
        ffi::meshopt_encodeMeshlet(
            result.as_mut_ptr(),
            result.len(),
            meshlet.vertices.as_ptr(),
            vertex_count,
            meshlet.triangles.as_ptr(),
            triangle_count,
        )
    };
    encoded(result, size)
}

/// Decodes meshlet data from an array of bytes generated by `encode_meshlet`, returning the
/// meshlet's vertex references and triangles (3 8-bit indices per triangle).
/// The decoder is safe to use for untrusted input, but it may produce garbage data.
///
/// * `vertex_count` and `triangle_count` must match those used during encoding exactly, and
///   `encoded` must be the exact data returned by `encode_meshlet`
/// * `vertex_count` may be 0, in which case the meshlet must contain just triangle data
pub fn decode_meshlet(
    encoded: &[u8],
    vertex_count: usize,
    triangle_count: usize,
) -> Result<(Vec<u32>, Vec<u8>)> {
    if vertex_count > 256 || triangle_count > 256 {
        return Err(Error::memory(
            "meshlet vertex and triangle counts must be at most 256",
        ));
    }
    let mut vertices: Vec<u32> = vec![0; vertex_count];
    // the decoder requires storage aligned to 4 bytes
    let mut triangles: Vec<u8> = vec![0; aligned_len::<u8>(triangle_count * 3, 4)];
    let result_code = unsafe {
        ffi::meshopt_decodeMeshlet(
            vertices.as_mut_ptr().cast(),
            vertex_count,
            mem::size_of::<u32>(),
            triangles.as_mut_ptr().cast(),
            triangle_count,
            3,
            encoded.as_ptr(),
            encoded.len(),
        )
    };
    triangles.truncate(triangle_count * 3);

    error_or(result_code, (vertices, triangles))
}

/// Decodes meshlet data from an array of bytes generated by `encode_meshlet`, returning 32-bit
/// vertex references and 32-bit packed triangles (stored as `(a) | (b << 8) | (c << 16)`).
/// The decoder is safe to use for untrusted input, but it may produce garbage data.
///
/// * `vertex_count` and `triangle_count` must match those used during encoding exactly, and
///   `encoded` must be the exact data returned by `encode_meshlet`
/// * `vertex_count` may be 0, in which case the meshlet must contain just triangle data
pub fn decode_meshlet_raw(
    encoded: &[u8],
    vertex_count: usize,
    triangle_count: usize,
) -> Result<(Vec<u32>, Vec<u32>)> {
    if vertex_count > 256 || triangle_count > 256 {
        return Err(Error::memory(
            "meshlet vertex and triangle counts must be at most 256",
        ));
    }
    // raw decoding requires storage further aligned to 16 bytes for efficient SIMD decoding
    let mut vertices: Vec<u32> = vec![0; aligned_len::<u32>(vertex_count, 16)];
    let mut triangles: Vec<u32> = vec![0; aligned_len::<u32>(triangle_count, 16)];
    let result_code = unsafe {
        ffi::meshopt_decodeMeshletRaw(
            vertices.as_mut_ptr(),
            vertex_count,
            triangles.as_mut_ptr(),
            triangle_count,
            encoded.as_ptr(),
            encoded.len(),
        )
    };
    vertices.truncate(vertex_count);
    triangles.truncate(triangle_count);

    error_or(result_code, (vertices, triangles))
}

/// Number of `T` elements needed to hold `len` elements rounded up to `align` bytes.
fn aligned_len<T>(len: usize, align: usize) -> usize {
    (len * mem::size_of::<T>()).next_multiple_of(align) / mem::size_of::<T>()
}

