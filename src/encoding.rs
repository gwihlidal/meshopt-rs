/// Component types that octahedral and color filters can store data in (`i8`, `u8`, `i16` or `u16`).
pub trait FilterComponent: Copy + Default + private::Sealed {}

impl FilterComponent for i8 {}
impl FilterComponent for u8 {}
impl FilterComponent for i16 {}
