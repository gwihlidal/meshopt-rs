/// Encodes arbitrary (finite) floating-point data with 8-bit exponent and K-bit integer mantissa
/// (1 <= K <= 24).
///
/// Can be used to encode data in a format that `decode_filter_exp` can decode. Exponent can be
/// shared between all components of a given vector (`N` components) or all values of a given
/// component, as defined by `mode`.
///
/// Panics if `N` is greater than 64.
pub fn encode_filter_exp<const N: usize>(
    data: &[[f32; N]],
    bits: i32,
    mode: EncodeExpMode,
) -> Vec<[u32; N]> {
    assert!(N <= 64, "vector component count ({N}) must be at most 64");
    let bits = bits.clamp(1, 24);
    let mut result: Vec<[u32; N]> = vec![[0; N]; data.len()];
    unsafe {
        ffi::meshopt_encodeFilterExp(
            result.as_mut_ptr().cast(),
            data.len(),
            mem::size_of::<[u32; N]>(),
            bits,
            data.as_ptr().cast(),
            mode as ffi::meshopt_EncodeExpMode,
        );
    }
    result
}

