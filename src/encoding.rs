    #[test]
    fn test_meshlet_codec_roundtrip() {
        // 32x32 quad grid
        const N: u32 = 32;
        let positions: Vec<[f32; 3]> = (0..=N)
            .flat_map(|y| (0..=N).map(move |x| [x as f32, y as f32, 0.0]))
            .collect();
        let indices: Vec<u32> = (0..N)
            .flat_map(|y| {
                (0..N).flat_map(move |x| {
                    let v = y * (N + 1) + x;
                    [v, v + 1, v + N + 1, v + 1, v + N + 2, v + N + 1]
                })
            })
            .collect();

        let adapter =
            VertexDataAdapter::new(typed_to_bytes(&positions), mem::size_of::<[f32; 3]>(), 0)
                .unwrap();
        let meshlets = build_meshlets(&indices, &adapter, 64, 124, 0.0);

        // the encoder may rotate triangle corners, so triangles are compared up to rotation
        let canonical = |triangles: &[u8]| -> Vec<[u8; 3]> {
            triangles
                .chunks(3)
                .map(|t| {
                    let mut t = [t[0], t[1], t[2]];
                    let min = (0..3).min_by_key(|&k| t[k]).unwrap();
                    t.rotate_left(min);
                    t
                })
                .collect()
        };

        for meshlet in meshlets.iter() {
            let mut vertices = meshlet.vertices.to_vec();
            let mut triangles = meshlet.triangles.to_vec();
            optimize_meshlet_level(&mut vertices, &mut triangles, 3);

            let encoded = encode_meshlet(Meshlet {
                vertices: &vertices,
                triangles: &triangles,
            })
            .unwrap();
            let (v, t) = decode_meshlet(&encoded, vertices.len(), triangles.len() / 3).unwrap();

            assert_eq!(v, vertices);
            assert_eq!(canonical(&t), canonical(&triangles));
        }
    }

