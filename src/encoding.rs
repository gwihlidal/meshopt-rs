    // Index encoder version is global state, so tests that encode indices must not run concurrently
    // with tests that change it
    static ENCODER_VERSION: Mutex<()> = Mutex::new(());

    const INDEX_SEQUENCE: [u32; 6] = [0, 1, 51, 2, 49, 1000];

    #[test]
    fn test_decode_index_sequence() {
        let encoded = [
            0xd1, 0x00, 0x04, 0xcd, 0x01, 0x04, 0x07, 0x98, 0x1f, 0x00, 0x00, 0x00, 0x00,
        ];
        let decoded = decode_index_sequence::<u32>(&encoded, INDEX_SEQUENCE.len()).unwrap();
        assert_eq!(decoded, INDEX_SEQUENCE);
    }

    #[test]
    fn test_index_sequence_roundtrip() {
        let encoded = {
            let _lock = ENCODER_VERSION.lock().unwrap();
            encode_index_sequence(&INDEX_SEQUENCE, 1001).unwrap()
        };
        let decoded = decode_index_sequence::<u16>(&encoded, INDEX_SEQUENCE.len()).unwrap();
        assert!(decoded.iter().map(|&i| u32::from(i)).eq(INDEX_SEQUENCE));
    }

