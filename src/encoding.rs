/// Checks that `T` is a vertex type the vertex codec supports.
fn check_codec_vertex_size<T>() -> Result<()> {
    let size = mem::size_of::<T>();
    if size == 0 || size > MAX_VERTEX_SIZE || !size.is_multiple_of(4) {
        return Err(Error::memory_dynamic(format!(
            "vertex size ({size}) must be a non-zero multiple of 4 no larger than {MAX_VERTEX_SIZE}"
        )));
    }
    Ok(())
}

/// Shrinks an encoder's output buffer to the size it reported, where 0 signals failure.
fn encoded(mut buffer: Vec<u8>, size: usize) -> Result<Vec<u8>> {
    if size == 0 || size > buffer.len() {
        return Err(Error::memory("failed to encode into the output buffer"));
    }
    buffer.truncate(size);
    Ok(buffer)
}

/// Encodes index data into an array of bytes that is generally much smaller (<1.5 bytes/triangle)
/// and compresses better (<1 bytes/triangle) compared to original.
///
/// For maximum efficiency the index buffer being encoded has to be optimized for vertex cache and
/// vertex fetch first.
pub fn encode_index_buffer(indices: &[u32], vertex_count: usize) -> Result<Vec<u8>> {
    if !indices.len().is_multiple_of(3) {
        return Err(Error::memory("index count must be a multiple of 3"));
    }
    let bounds = unsafe { ffi::meshopt_encodeIndexBufferBound(indices.len(), vertex_count) };
    let mut result: Vec<u8> = vec![0; bounds];
    let size = unsafe {
        ffi::meshopt_encodeIndexBuffer(
            result.as_mut_ptr(),
            result.len(),
            indices.as_ptr(),
            indices.len(),
        )
    };
    encoded(result, size)
}

/// Decodes index data from an array of bytes generated by `encode_index_buffer`.
/// The decoder is safe to use for untrusted input, but it may produce garbage
/// data (e.g. out of range indices).
pub fn decode_index_buffer<T: IndexType>(encoded: &[u8], index_count: usize) -> Result<Vec<T>> {
    if !index_count.is_multiple_of(3) {
        return Err(Error::memory("index count must be a multiple of 3"));
    }

    let mut result: Vec<T> = vec![Default::default(); index_count];
    let result_code = unsafe {
        ffi::meshopt_decodeIndexBuffer(
            result.as_mut_ptr().cast(),
            index_count,
            mem::size_of::<T>(),
            encoded.as_ptr(),
            encoded.len(),
        )
    };

    error_or(result_code, result)
}

/// Sets index encoder format version (defaults to 1).
///
/// `version` must specify the data format version to encode; valid values are 0 (decodable by all
/// library versions) and 1 (decodable by 0.14+).
///
/// # Safety
///
/// This function is not thread safe and must not be called concurrently with
/// `encode_index_buffer`/`encode_index_sequence`.
pub unsafe fn encode_index_version(version: i32) {
    unsafe { ffi::meshopt_encodeIndexVersion(version) }
}

/// Returns format version of the encoded index buffer/sequence, or `None` if the buffer header is
/// invalid.
///
/// Note that a valid version doesn't guarantee that the buffer will be decoded correctly if the
/// input is malformed.
pub fn decode_index_version(encoded: &[u8]) -> Option<i32> {
    let version = unsafe { ffi::meshopt_decodeIndexVersion(encoded.as_ptr(), encoded.len()) };
    (version >= 0).then_some(version)
}

