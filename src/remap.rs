/// Generates a vertex remap table from the vertex buffer and an optional index buffer and returns number of unique vertices.
///
/// As a result, all vertices that are binary equivalent map to the same (new) location, with no gaps in the resulting sequence.
/// Resulting remap table maps old vertices to new vertices and can be used in `remap_vertex_buffer`/`remap_index_buffer`.
///
/// The `indices` can be `None` if the input is unindexed.
pub fn generate_vertex_remap<T: NoUninit>(
    vertices: &[T],
    indices: Option<&[u32]>,
) -> (usize, Vec<u32>) {
    check_vertex_size::<T>();
    if let Some(indices) = indices {
        check_indices(indices, vertices.len());
    }
    let mut remap: Vec<u32> = vec![0; vertices.len()];
    let vertex_count = unsafe {
        match indices {
            Some(indices) => ffi::meshopt_generateVertexRemap(
                remap.as_mut_ptr().cast(),
                indices.as_ptr().cast(),
                indices.len(),
                vertices.as_ptr().cast(),
                vertices.len(),
                mem::size_of::<T>(),
            ),
            None => ffi::meshopt_generateVertexRemap(
                remap.as_mut_ptr(),
                std::ptr::null(),
                vertices.len(),
                vertices.as_ptr().cast(),
                vertices.len(),
                mem::size_of::<T>(),
            ),
        }
    };
    (vertex_count, remap)
}

/// Generates a vertex remap table from multiple vertex streams and an optional index buffer and returns number of unique vertices.
///
/// As a result, all vertices that are binary equivalent map to the same (new) location, with no gaps in the resulting sequence.
/// Resulting remap table maps old vertices to new vertices and can be used in `remap_vertex_buffer`/`remap_index_buffer`.
///
/// To remap vertex buffers, you will need to call `remap_vertex_buffer` for each vertex stream.
///
/// The `indices` can be `None` if the input is unindexed.
pub fn generate_vertex_remap_multi(
    vertex_count: usize,
    streams: &[VertexStream<'_>],
    indices: Option<&[u32]>,
) -> (usize, Vec<u32>) {
    if let Some(indices) = indices {
        check_indices(indices, vertex_count);
    }
    let streams = ffi_streams(streams, vertex_count);
    let mut remap: Vec<u32> = vec![0; vertex_count];
    let vertex_count = unsafe {
        match indices {
            Some(indices) => ffi::meshopt_generateVertexRemapMulti(
                remap.as_mut_ptr(),
                indices.as_ptr(),
                indices.len(),
                vertex_count,
                streams.as_ptr(),
                streams.len(),
            ),
            None => ffi::meshopt_generateVertexRemapMulti(
                remap.as_mut_ptr(),
                std::ptr::null(),
                vertex_count,
                vertex_count,
                streams.as_ptr(),
                streams.len(),
            ),
        }
    };
    (vertex_count, remap)
}

/// Generate index buffer from the source index buffer and remap table generated by `generate_vertex_remap`.
///
/// `indices` can be `None` if the input is unindexed.
pub fn remap_index_buffer(indices: Option<&[u32]>, vertex_count: usize, remap: &[u32]) -> Vec<u32> {
    match indices {
        Some(indices) => check_indices(indices, remap.len()),
        None => assert!(
            remap.len() >= vertex_count,
            "remap table must have an entry for each vertex"
        ),
    }
    let mut result: Vec<u32> = Vec::new();
    if let Some(indices) = indices {
        result.resize(indices.len(), 0u32);
        unsafe {
            ffi::meshopt_remapIndexBuffer(
                result.as_mut_ptr(),
                indices.as_ptr(),
                indices.len(),
                remap.as_ptr(),
            );
        }
    } else {
        result.resize(vertex_count, 0u32);
        unsafe {
            ffi::meshopt_remapIndexBuffer(
                result.as_mut_ptr(),
                std::ptr::null(),
                vertex_count,
                remap.as_ptr(),
            );
        }
    }

    result
}

/// Generates vertex buffer from the source vertex buffer and remap table generated by `generate_vertex_remap`.
///
/// `vertex_count` is the number of vertices in the result; entries of `remap` that are `u32::MAX`
/// mark vertices that are dropped.
pub fn remap_vertex_buffer<T: Pod>(vertices: &[T], vertex_count: usize, remap: &[u32]) -> Vec<T> {
    check_vertex_size::<T>();
    assert!(
        remap.len() >= vertices.len(),
        "remap table must have an entry for each vertex"
    );
    // unused vertices are marked with !0 and skipped
    let used = remap[..vertices.len()].iter().filter(|&&v| v != u32::MAX);
    if let Some(&index) = used.clone().find(|&&v| v as usize >= vertex_count) {
        panic!("remap entry ({index}) must be less than vertex count ({vertex_count})");
    }
    let mut result: Vec<T> = vec![T::zeroed(); vertex_count];
    unsafe {
        ffi::meshopt_remapVertexBuffer(
            result.as_mut_ptr().cast(),
            vertices.as_ptr().cast(),
            vertices.len(),
            mem::size_of::<T>(),
            remap.as_ptr(),
        );
    }
    result
}

/// Generates a remap table that maps all vertices with the same position to the same (existing) index.
///
/// Similarly to `generate_shadow_indices`, this can be helpful to pre-process meshes for position-only rendering.
/// This can also be used to implement algorithms that require positional-only connectivity, such as hierarchical simplification.
pub fn generate_position_remap(vertices: &VertexDataAdapter<'_>) -> Vec<u32> {
    let mut remap: Vec<u32> = vec![0; vertices.vertex_count];
    unsafe {
        ffi::meshopt_generatePositionRemap(
            remap.as_mut_ptr(),
            vertices.pos_ptr(),
            vertices.vertex_count,
            vertices.vertex_stride,
        );
    }
    remap
}

/// Generates a remap table that maps all vertices with the same position to the same (existing) index.
///
/// Similarly to `generate_shadow_indices`, this can be helpful to pre-process meshes for position-only rendering.
/// This can also be used to implement algorithms that require positional-only connectivity, such as hierarchical simplification.
pub fn generate_position_remap_decoder<T: DecodePosition>(vertices: &[T]) -> Vec<u32> {
    let positions = vertices
        .iter()
        .map(|vertex| vertex.decode_position())
        .collect::<Vec<[f32; 3]>>();
    let mut remap: Vec<u32> = vec![0; positions.len()];
    unsafe {
        ffi::meshopt_generatePositionRemap(
            remap.as_mut_ptr(),
            positions.as_ptr().cast(),
            positions.len(),
            mem::size_of::<f32>() * 3,
        );
    }
    remap
}

/// Filters out redundant triangles from the index buffer.
///
/// Triangles are considered redundant if they are degenerate (two vertices have the same vertex key)
/// or duplicate (matching triangle was present earlier). All bytes of each vertex are compared for
/// equality; typically `vertices` should contain only the position attribute.
///
/// Note that duplicate triangles with opposite windings are preserved, as they may be needed for
/// double-sided rendering.
pub fn filter_index_buffer<T: NoUninit>(indices: &[u32], vertices: &[T]) -> Vec<u32> {
    check_vertex_size::<T>();
    check_triangles(indices, vertices.len());
    let mut result: Vec<u32> = vec![0; indices.len()];
    let index_count = unsafe {
        ffi::meshopt_filterIndexBuffer(
            result.as_mut_ptr(),
            indices.as_ptr(),
            indices.len(),
            vertices.as_ptr().cast(),
            vertices.len(),
            mem::size_of::<T>(),
            mem::size_of::<T>(),
        )
    };
    result.truncate(index_count);
    result
}

/// Filters out redundant triangles from the index buffer, comparing vertices using multiple vertex streams.
///
/// Triangles are considered redundant if they are degenerate (two vertices have the same vertex key)
/// or duplicate (matching triangle was present earlier). All bytes in specified streams are compared
/// for equality; streams should include attributes relevant for position transform (e.g. bone influences).
///
/// Note that duplicate triangles with opposite windings are preserved, as they may be needed for
/// double-sided rendering.
///
/// At most 16 streams are supported.
pub fn filter_index_buffer_multi(
    indices: &[u32],
    vertex_count: usize,
    streams: &[VertexStream<'_>],
) -> Vec<u32> {
    check_triangles(indices, vertex_count);
    let streams = ffi_streams(streams, vertex_count);
    let mut result: Vec<u32> = vec![0; indices.len()];
    let index_count = unsafe {
        ffi::meshopt_filterIndexBufferMulti(
            result.as_mut_ptr(),
            indices.as_ptr(),
            indices.len(),
            vertex_count,
            streams.as_ptr(),
            streams.len(),
        )
    };
    result.truncate(index_count);
    result
}

/// Generates a vertex remap table from the vertex buffer and an optional index buffer and returns number of unique vertices.
///
/// As a result, all vertices that are equivalent map to the same (new) location, with no gaps in the resulting sequence.
/// Equivalence is checked in two steps: vertex positions are compared for equality, and then `callback` is called.
/// Resulting remap table maps old vertices to new vertices and can be used in `remap_vertex_buffer`/`remap_index_buffer`.
///
/// The `indices` can be `None` if the input is unindexed.
/// `callback` should return `true` if vertices with specified indices are equivalent and `false` if they are not.
pub fn generate_vertex_remap_custom<F: FnMut(u32, u32) -> bool>(
    vertices: &VertexDataAdapter<'_>,
    indices: Option<&[u32]>,
    callback: F,
) -> (usize, Vec<u32>) {
    generate_vertex_remap_custom_raw(
        vertices.pos_ptr(),
        vertices.vertex_count,
        vertices.vertex_stride,
        indices,
        callback,
    )
}

/// Generates a vertex remap table from the vertex buffer and an optional index buffer and returns number of unique vertices.
///
/// See [`generate_vertex_remap_custom`] for details.
pub fn generate_vertex_remap_custom_decoder<T: DecodePosition, F: FnMut(u32, u32) -> bool>(
    vertices: &[T],
    indices: Option<&[u32]>,
    callback: F,
) -> (usize, Vec<u32>) {
    let positions = vertices
        .iter()
        .map(|vertex| vertex.decode_position())
        .collect::<Vec<[f32; 3]>>();
    generate_vertex_remap_custom_raw(
        positions.as_ptr().cast(),
        positions.len(),
        mem::size_of::<f32>() * 3,
        indices,
        callback,
    )
}

fn generate_vertex_remap_custom_raw<F: FnMut(u32, u32) -> bool>(
    vertex_positions: *const f32,
    vertex_count: usize,
    vertex_positions_stride: usize,
    indices: Option<&[u32]>,
    mut callback: F,
) -> (usize, Vec<u32>) {
    if let Some(indices) = indices {
        check_indices(indices, vertex_count);
    }
    unsafe extern "C" fn compare<F: FnMut(u32, u32) -> bool>(
        context: *mut c_void,
        lhs: c_uint,
        rhs: c_uint,
    ) -> c_int {
        let callback = unsafe { &mut *context.cast::<F>() };
        c_int::from(callback(lhs, rhs))
    }

    let mut remap: Vec<u32> = vec![0; vertex_count];
    let unique_count = unsafe {
        ffi::meshopt_generateVertexRemapCustom(
            remap.as_mut_ptr(),
            indices.map_or(std::ptr::null(), <[u32]>::as_ptr),
            indices.map_or(vertex_count, <[u32]>::len),
            vertex_positions,
            vertex_count,
            vertex_positions_stride,
            Some(compare::<F>),
            std::ptr::from_mut(&mut callback).cast(),
        )
    };
    (unique_count, remap)
}

/// Generate index buffer that can be used as a geometry shader input with triangle adjacency topology.
///
/// Each triangle is converted into a 6-vertex patch with the following layout:
/// - 0, 2, 4: original triangle vertices
/// - 1, 3, 5: vertices adjacent to edges 02, 24 and 40
///
/// The resulting patch can be rendered with geometry shaders using e.g. `VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST_WITH_ADJACENCY`.
/// This can be used to implement algorithms like silhouette detection/expansion and other forms of GS-driven rendering.
pub fn generate_adjacency_indices(indices: &[u32], vertices: &VertexDataAdapter<'_>) -> Vec<u32> {
    check_triangles(indices, vertices.vertex_count);
    let mut result: Vec<u32> = vec![0; indices.len() * 2];
    unsafe {
        ffi::meshopt_generateAdjacencyIndexBuffer(
            result.as_mut_ptr(),
            indices.as_ptr(),
            indices.len(),
            vertices.pos_ptr(),
            vertices.vertex_count,
            vertices.vertex_stride,
        );
    }
    result
}

